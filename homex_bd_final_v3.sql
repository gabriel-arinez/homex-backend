        RAISE EXCEPTION 'No existe ESTADO_PEDIDO.CONFIRMADO activo';
    END IF;

    INSERT INTO pedidos (
        proforma_id, estado_id, created_by_id, updated_by_id
    ) VALUES (
        NEW.id,
        v_estado_confirmado,
        COALESCE(NEW.updated_by_id, NEW.created_by_id),
        COALESCE(NEW.updated_by_id, NEW.created_by_id)
    );

    RETURN NEW;
END;
$$;

